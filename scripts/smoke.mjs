const rangeAudit = await page.evaluate(async () => {
  const controls = [...document.querySelectorAll('input[type="range"]')]
  const unnamed = controls.filter((input) => !input.getAttribute('aria-label') && !input.closest('label')?.textContent?.trim())
  if (unnamed.length) throw new Error(`${unnamed.length} range controls have no accessible name`)
  let changed = 0
  for (const input of controls.filter((control) => !control.disabled)) {
    const original = input.value
    const min = Number(input.min || 0)
    const max = Number(input.max || 100)
    const midpoint = String(min + (max - min) * (original === String(min + (max - min) / 2) ? 0.37 : 0.5))
    const setValue = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set
    setValue?.call(input, midpoint)
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
    await new Promise((resolve) => requestAnimationFrame(() => resolve()))
    if (input.value === original) throw new Error(`Range control did not update: ${input.getAttribute('aria-label') || input.closest('label')?.textContent}`)
    changed += 1
    setValue?.call(input, original)
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
    await new Promise((resolve) => requestAnimationFrame(() => resolve()))
  }
  return { total: controls.length, changed }
})
