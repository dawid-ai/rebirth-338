function makeToneWav(seconds = 0.18, frequency = 110) {
  const rate = 44_100
  const frames = Math.floor(rate * seconds)
  const output = Buffer.alloc(44 + frames * 2)
  output.write('RIFF', 0); output.writeUInt32LE(output.length - 8, 4); output.write('WAVE', 8)
  output.write('fmt ', 12); output.writeUInt32LE(16, 16); output.writeUInt16LE(1, 20); output.writeUInt16LE(1, 22)
  output.writeUInt32LE(rate, 24); output.writeUInt32LE(rate * 2, 28); output.writeUInt16LE(2, 32); output.writeUInt16LE(16, 34)
  output.write('data', 36); output.writeUInt32LE(frames * 2, 40)
  for (let frame = 0; frame < frames; frame += 1) {
    const envelope = Math.max(0, 1 - frame / frames)
    output.writeInt16LE(Math.round(Math.sin(frame / rate * frequency * Math.PI * 2) * envelope * 14_000), 44 + frame * 2)
  }
  return output
}

